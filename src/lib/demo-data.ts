export function buildDemoSnapshot(): LibrarySnapshot {
  return {
    artists: artists.map((artist) => ({
      id: artist.id,
      name: artist.name,
      tags: artist.tags,
      tagSource: artist.tags && artist.tags.length > 0 ? "demo" : null,
    })),
    tracks: tracks.map((track) => ({
      id: track.id,
      uri: `spotify:track:${track.id}`,
      name: track.name,
      album: track.album,
      imageUrl: null,
      durationMs: track.durationMs,
      liked: track.liked,
      artistIds: track.artistIds,
    })),
    playlists: playlists.map((playlist) => ({
      id: playlist.id,
      name: playlist.name,
      snapshotId: `demo-${playlist.id}`,
      ownerId: DEMO_USER,
      trackIds: tracks.filter((track) => track.playlistIds.includes(playlist.id)).map((track) => track.id),
    })),
  };
}

